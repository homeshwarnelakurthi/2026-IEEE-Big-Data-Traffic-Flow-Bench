"""Cell-transmission-model (CTM) fill for Task 1 targets inside Task 2 blank blocks (T+5..T+90, every mainline link blank).

Inside a block the mainline is blank but ramp flows are still released (about 78% observed, as outside blocks), and the
data are generated by a CTM/LWR model with the released triangular fundamental diagrams. So instead of learning the gap we
simulate it:
  - cells: consecutive mainline links merged until at least LMIN km (some links are 1 m long; CFL would force tiny steps)
  - initial state: density q/v of every link at the origin row T (interpolated along the corridor where missing)
  - upstream boundary: flow of the first link, linear in time between T and the first observed row after the block
  - downstream boundary: supply from the last link's density, linear in time between T and after the block
  - ramps: released on/off-ramp flows (gaps interpolated in time); off-ramps split FIFO, on-ramps merge proportionally
  - Godunov/CTM update with demand min(vf k, C) and supply min(C, w (kj - k)), w = C / (kj - kc)
Output per block cell: 5-minute mean flow and speed (= mean flow / mean density) of the cell holding the link.

eval: February days carrying March's window schedule (same simulation as t1_gapfill.py eval: protected hour T-55..T
      unmasked); dumps per-cell predictions for t1_blocks_blend3.py. Usage: python t1_ctm_gap.py eval <out.csv> [panel]
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from common import RELEASE, load, meta, panels, slot_of
from t1_common import targets

B, LMIN = 18, 0.1  # block length (slots), minimum CTM cell length (km)
USE_RAMPS = False  # released ramp flows (see fill_block) vs net sources inferred from the mainline
CSLACK = 1.05  # capacity slack: free-flow links already carry flows at the released capacity
CALIB = True  # calibrate active bottlenecks and the congested branch from the origin row


def chain(panel):
    """Merged CTM cells for the corridor (mainline links in milepost order, same order as meta())."""
    net = RELEASE / "corridors" / panel / "network"
    top = pd.read_csv(net / "lwr_mainline_topology.csv", dtype={"on_ramp_link_ids": str, "off_ramp_link_ids": str}).sort_values("order_index")
    fd = pd.read_csv(net / "fd_parameters.csv").drop_duplicates("link_id").set_index("link_id")
    links = top.mainline_link_id.astype(str).tolist()
    assert links == meta(panel).link_id.tolist(), "topology order differs from meta order"
    L = top.length_km.to_numpy(float); C = fd.loc[links, "capacity_vph"].to_numpy(float)
    vf = fd.loc[links, "free_speed_kmh"].to_numpy(float); kj = fd.loc[links, "k_jam"].to_numpy(float)
    on = top.on_ramp_link_ids.fillna("").str.split(";").tolist(); off = top.off_ramp_link_ids.fillna("").str.split(";").tolist()
    cell, cur, acc = np.zeros(len(links), int), 0, 0.0
    for i in range(len(links)):
        cell[i] = cur; acc += L[i]
        if acc >= LMIN and i < len(links) - 1:
            cur += 1; acc = 0.0
    n = cur + 1
    cL = np.bincount(cell, L, n)
    cvf = np.bincount(cell, L * vf, n) / cL  # length-weighted free speed
    ckj = np.bincount(cell, L * kj, n) / cL  # length-weighted jam density (veh/km, all lanes)
    cC = CSLACK * np.array([C[cell == c].min() for c in range(n)])  # bottleneck capacity of the merged links
    con = [[r for i in np.nonzero(cell == c)[0] for r in on[i] if r] for c in range(n)]
    coff = [[r for i in np.nonzero(cell == c)[0] for r in off[i] if r] for c in range(n)]
    return dict(cell=cell, n=n, L=cL, vf=cvf, kj=ckj, C=cC, kc=cC / cvf, w=cC / np.maximum(ckj - cC / cvf, 1e-3), on=con, off=coff)


def ramp_matrix(panel, split, date):
    """{ramp_link_id: (288,) flow_vph}, gaps interpolated in time (only released, non-null values are used)."""
    f = [p for p in (RELEASE / "corridors" / panel / split / "ramp_states").glob("*/*.parquet") if date.replace("-", "_") in p.name]
    if not f:
        return {}
    r = pd.read_parquet(f[0], columns=["timestamp", "ramp_link_id", "flow_vph"])
    ts = r.timestamp.astype(str); r["s"] = (ts.str[11:13].astype(int) * 60 + ts.str[14:16].astype(int)) // 5; r = r[r.flow_vph.notna()]
    out = {}
    for rid, g in r.groupby("ramp_link_id"):
        a = np.full(288, np.nan); a[g.s.to_numpy()] = g.flow_vph.to_numpy()
        out[str(rid)] = pd.Series(a).interpolate(limit_direction="both").fillna(0).to_numpy()
    return out


def interp_density(v, q, cell, n, prof_k):
    """Cell densities from one row of link speed/flow (NaN = unknown): q/v averaged per cell, gaps filled along the corridor."""
    k = q / np.maximum(v, 1.0)
    s = np.bincount(cell[np.isfinite(k)], k[np.isfinite(k)], n); c = np.bincount(cell[np.isfinite(k)], minlength=n)
    ck = np.where(c > 0, s / np.maximum(c, 1), np.nan)
    ck = pd.Series(ck).interpolate(limit_direction="both").to_numpy()
    return np.where(np.isfinite(ck), ck, prof_k)


def simulate(ch, k0, inflow, k_end, ramps_on, ramps_off, nslot=B):
    """Run the CTM for nslot 5-minute slots. inflow (nslot,), k_end (nslot,) downstream-cell density for the supply,
    ramps_*: (n, nslot) cell-level ramp flows. Returns mean flow and mean density per cell and slot (nslot, n)."""
    n, L, vf, C, kj, w = ch["n"], ch["L"], ch["vf"], ch["C"], ch["kj"], ch["w"]
    dt = 0.9 * (L / np.maximum(vf, w)).min()  # hours, CFL
    sub = int(np.ceil((5 / 60) / dt)); dt = (5 / 60) / sub
    k = k0.copy(); rq = np.zeros(n)  # on-ramp queues (veh)
    Q, K = np.zeros((nslot, n)), np.zeros((nslot, n))
    for s in range(nslot):
        on, off = ramps_on[:, s], ramps_off[:, s]
        Cend = min(C[-1], w[-1] * max(kj[-1] - k_end[s], 0.0)) if k_end[s] > ch["kc"][-1] else C[-1]
        for _ in range(sub):
            D = np.minimum(vf * k, C); S = np.minimum(C, w * np.maximum(kj - k, 0))
            beta = np.clip(off / np.maximum(D, 1e-6), 0, 0.9)
            Dm = (1 - beta) * D  # mainline sending flow of each cell after its off-ramps
            R = on + rq / dt  # on-ramp demand incl. queued vehicles
            # flux across cell boundaries: into cell i+1 from cell i and the on-ramps of cell i+1
            dem = Dm[:-1] + R[1:]; f = np.minimum(1.0, S[1:] / np.maximum(dem, 1e-6))
            fm = f * Dm[:-1]; fr = f * R[1:]
            out_main = np.append(fm, min(Dm[-1], Cend))  # last cell drains into the downstream boundary
            fout = out_main / np.maximum(1 - beta, 1e-6) * beta  # FIFO off-ramp flow
            fin = np.empty(n); fin[0] = min(inflow[s], S[0]); fin[1:] = fm + fr
            rq[1:] = np.maximum(rq[1:] + (R[1:] - fr) * dt - rq[1:], 0)  # unmet on-ramp demand stays queued
            k = np.maximum(k + dt / L * (fin - out_main - fout), 0)
            Q[s] += (fin + out_main + fout) / 2 / sub; K[s] += k / sub
    return Q, K


def fill_block(ch, v, q, o, ramps, pk):
    """CTM prediction (speed, flow) for the 18 block slots o+1..o+18 on every link. v, q: (288, links) visible data."""
    cell, n = ch["cell"], ch["n"]
    k0 = interp_density(v[o], q[o], cell, n, pk[o])
    after = next((s for s in range(o + B + 1, min(o + B + 19, 288)) if np.isfinite(q[s, :3]).any()), None)
    first = lambda s: np.nanmean(q[s, :3]) if np.isfinite(q[s, :3]).any() else np.nan
    q_up0 = first(o) if np.isfinite(first(o)) else np.nanmean(q[max(o - 3, 0):o + 1, :3])
    q_up1 = first(after) if after is not None else q_up0
    kend0 = interp_density(v[o], q[o], cell, n, pk[o])[-1]
    kend1 = interp_density(v[after], q[after], cell, n, pk[after])[-1] if after is not None else kend0
    span = (after - o) if after is not None else B + 1
    a = np.arange(1, B + 1) / span
    inflow = (1 - a) * q_up0 + a * q_up1; k_end = (1 - a) * kend0 + a * kend1
    if USE_RAMPS:
        ron, roff = np.zeros((n, B)), np.zeros((n, B))
        for c in range(n):
            for r in ch["on"][c]:
                if r in ramps: ron[c] += ramps[r][o + 1:o + B + 1]
            for r in ch["off"][c]:
                if r in ramps: roff[c] += ramps[r][o + 1:o + B + 1]
    else:
        # the released ramp flows do not balance the mainline (on - off adds ~+3600 veh/h along D12_I5_S while the mainline
        # loses ~100), so the net source of each cell is taken from the mainline itself: the cell-to-cell flow change
        # before the block and after it, linear in time across the block
        def cell_flow(rows):
            x = np.nanmean(q[rows], 0) if np.isfinite(q[rows]).any() else np.full(q.shape[1], np.nan)
            s_ = np.bincount(cell[np.isfinite(x)], x[np.isfinite(x)], n); c_ = np.bincount(cell[np.isfinite(x)], minlength=n)
            return pd.Series(np.where(c_ > 0, s_ / np.maximum(c_, 1), np.nan)).interpolate(limit_direction="both").to_numpy()
        f0 = cell_flow(slice(max(o - 2, 0), o + 1))
        f1 = cell_flow(slice(after, min(after + 3, 288))) if after is not None else f0
        net = np.outer(np.r_[0, np.diff(f0)], 1 - a) + np.outer(np.r_[0, np.diff(f1)], a)
        ron, roff = np.maximum(net, 0), np.maximum(-net, 0)
    if CALIB:
        # the released FDs do not reproduce the queues (a 26 km/h queue carrying 6400 veh/h sits off the congested branch
        # kj = 400, w = 25), so active bottlenecks are calibrated from the origin row: the cell just downstream of each
        # queue head gets the queue's discharge flow as capacity, and queue cells get a jam density through the observed point
        ch = dict(ch); ch["C"] = ch["C"].copy(); ch["kj"] = ch["kj"].copy()
        vc = np.bincount(cell, np.nan_to_num(v[o], nan=0), n) / np.maximum(np.bincount(cell, np.isfinite(v[o]), n), 1)
        has = np.bincount(cell, np.isfinite(v[o]), n) > 0
        qc = np.bincount(cell, np.nan_to_num(q[o], nan=0), n) / np.maximum(np.bincount(cell, np.isfinite(q[o]), n), 1)
        cong = has & (vc < 0.6 * ch["vf"])
        for c in np.nonzero(cong & ~np.r_[cong[1:], False])[0]:  # queue heads
            if c + 1 < n:
                ch["C"][c + 1] = min(ch["C"][c + 1], max(qc[c], 0.3 * ch["C"][c + 1]))
        kq = np.where(cong, qc / np.maximum(vc, 1), np.nan)
        ch["kj"] = np.where(cong, np.maximum(kq + qc / ch["w"], ch["kj"]), ch["kj"])
        ch["kc"] = ch["C"] / ch["vf"]
    Q, K = simulate(ch, k0, np.nan_to_num(inflow, nan=0.3 * ch["C"][0]), k_end, ron, roff)
    sp = np.clip(Q / np.maximum(K, 1e-3), 3, ch["vf"] * 1.05)
    return sp[:, cell], Q[:, cell]


def evaluate(out_csv, only=None):
    rows = []
    for panel in (only or panels()):
        wp = RELEASE / "task2" / panel / "validation" / "window_index.csv"
        if not wp.exists():
            continue
        wi = pd.read_csv(wp); full = load(panel, "train", masked=False); masked = load(panel, "train", masked=True)
        dates = list(full["dates"]); feb = [i for i, d in enumerate(dates) if d.startswith("2031-02")]
        tgt = targets(panel, "train"); ch = chain(panel); m = meta(panel); lanes = m.lanes.to_numpy(float)
        months = np.array([d[:7] for d in dates]); dows = pd.to_datetime(pd.Series(dates)).dt.day_of_week.to_numpy()
        sched = {}
        for w in wi.itertuples():
            if int(w.date[8:10]) <= len(feb):
                sched.setdefault(feb[int(w.date[8:10]) - 1], []).append(slot_of(w.forecast_origin))
        for d, origins in sched.items():
            sel = (months != "2031-02") & ((dows >= 5) == (dows[d] >= 5))
            with np.errstate(all="ignore"):
                pk = np.nanmean(full["flow"][sel] / np.maximum(full["speed"][sel], 1), 0)  # (288, links) profile density
            pk = np.stack([np.bincount(ch["cell"], np.nan_to_num(r), ch["n"]) / np.bincount(ch["cell"], minlength=ch["n"]) for r in pk])
            v, q = masked["speed"][d].copy(), masked["flow"][d].copy()
            for o in origins:  # protected history hour, then all blocks of the day blank at once
                v[max(o - 11, 0):o + 1] = full["speed"][d, max(o - 11, 0):o + 1]; q[max(o - 11, 0):o + 1] = full["flow"][d, max(o - 11, 0):o + 1]
            for o in origins:
                v[o + 1:o + B + 1] = np.nan; q[o + 1:o + B + 1] = np.nan
            ramps = ramp_matrix(panel, "train", dates[d])
            for o in origins:
                sp, fl = fill_block(ch, v, q, o, ramps, pk)
                for i, s in enumerate(range(o + 1, min(o + B + 1, 288))):
                    j = np.nonzero(tgt[d][s] & np.isfinite(full["speed"][d, s]) & np.isfinite(full["flow"][d, s]))[0]
                    rows.append(pd.DataFrame({"panel": panel, "day": dates[d], "slot": s, "j": j, "v_ctm": sp[i, j], "q_ctm": fl[i, j],
                                              "v_true": full["speed"][d, s, j], "q_true": full["flow"][d, s, j], "lanes": lanes[j]}))
        print(panel, "days", len(sched), flush=True)
    r = pd.concat(rows).drop_duplicates(["panel", "day", "slot", "j"])
    r.to_csv(out_csv, index=False)
    rv = np.sqrt(((r.v_ctm - r.v_true) ** 2).mean()); rq = np.sqrt((((r.q_ctm - r.q_true) / r.lanes) ** 2).mean())
    print(f"IN-BLOCK ctm: n={len(r)} speed RMSE {rv:.3f}  flow/lane RMSE {rq:.2f}  S~{0.54*(1-rv/25)+0.46*(1-rq/600):.4f}")


if __name__ == "__main__":
    if sys.argv[1] == "eval":
        evaluate(sys.argv[2], sys.argv[3:] or None)
